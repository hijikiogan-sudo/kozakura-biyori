"""Generate dark.css from style.css. Run after changing colors: python3 scripts/generate_dark_css.py

Light surfaces (backgrounds, borders, shadows) become dark surfaces and dark text becomes light text.
Saturated accents such as buttons and the white text on them keep their original colors.
"""
import colorsys
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
HEX = re.compile(r'#([0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{3,4})\b|\bwhite\b')
# Hand-tuned rules appended after the generated ones, for accents that should stay recognizable.
EXTRA = '.flight-start{background:#3d5a42;border-color:#4d6e52;color:#eef3e8}'
TEXT_PROPS = {'color', '--deep', '--muted'}
SURFACE_PROPS = {'background', 'background-color', 'border', 'border-color', 'border-top', 'border-bottom', 'border-left', 'border-right',
                 'border-top-color', 'border-right-color', 'border-bottom-color', 'border-left-color', 'box-shadow', 'outline',
                 'fill', 'stroke', 'text-shadow', '--cream', '--line', '--shadow', '--tint'}


def parse(token):
    if token == 'white':
        return 1, 1, 1, ''
    h = token[1:]
    if len(h) in (3, 4):
        h = ''.join(c * 2 for c in h)
    r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
    return r, g, b, h[6:]


def fmt(r, g, b, alpha):
    return '#' + ''.join(f'{round(max(0, min(1, v)) * 255):02x}' for v in (r, g, b)) + alpha


def surface(token):
    r, g, b, alpha = parse(token)
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    # Mid-tone and vivid accents (buttons, the pink flight button) keep their light-mode color.
    if l <= 0.7 or (s > 0.5 and l < 0.88):
        return token
    return fmt(*colorsys.hls_to_rgb(h, 0.13 + (1 - l) * 0.6, s * 0.22), alpha)


def text(token):
    r, g, b, alpha = parse(token)
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    if l >= 0.55:
        return token
    return fmt(*colorsys.hls_to_rgb(h, 0.9 - l * 0.4, s * 0.5), alpha)


def convert(decls):
    out = []
    for decl in decls.split(';'):
        if ':' not in decl:
            continue
        prop, value = decl.split(':', 1)
        prop = prop.strip()
        mapper = text if prop in TEXT_PROPS else surface if prop in SURFACE_PROPS else None
        if not mapper or not HEX.search(value):
            continue
        new = HEX.sub(lambda m: mapper(m.group(0)), value)
        if new != value:
            out.append(f'{prop}:{new}')
    return ';'.join(out)


def blocks(css):
    """Yield (prelude, body) pairs at one nesting level."""
    i = 0
    while i < len(css):
        open_at = css.find('{', i)
        if open_at < 0:
            return
        depth, j = 1, open_at + 1
        while depth:
            depth += {'{': 1, '}': -1}.get(css[j], 0)
            j += 1
        prelude = css[i:open_at].strip()
        if ';' in prelude:  # e.g. @charset before the first rule
            prelude = prelude.rsplit(';', 1)[1].strip()
        yield prelude, css[open_at + 1:j - 1]
        i = j


def rules(css):
    out = []
    for prelude, body in blocks(css):
        if prelude.startswith('@keyframes'):
            continue
        if prelude.startswith('@'):
            inner = rules(body)
            if inner:
                out.append(f'{prelude}{{{inner}}}')
            continue
        converted = convert(body)
        if converted:
            out.append(f'{prelude}{{{converted}}}')
    return ''.join(out)


def main():
    css = (ROOT / 'style.css').read_text(encoding='utf-8')
    header = '/* Generated by scripts/generate_dark_css.py from style.css. Do not edit by hand. */\n'
    (ROOT / 'dark.css').write_text(header + ':root{color-scheme:dark}' + rules(css) + EXTRA + '\n', encoding='utf-8')


if __name__ == '__main__':
    main()
